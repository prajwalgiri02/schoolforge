import fs from 'node:fs';
import path from 'node:path';
import { buildSites, buildThemeCss, RETIRED_COMPONENTS, slugify, usedComponents, validateConfig } from './config.js';
import { exists, hashContents, hashFile, listFiles, readJson, removeFile, writeFile, writeJson } from './fsutil.js';
import { LOCK_FILE, PROJECT_CONFIG_FILE, RUNTIME_DIR, SAMPLE_FILES_DIR } from './paths.js';
import { getComponent, getTheme, listComponents } from './registry.js';
import { getTarget } from './targets/index.js';

export const GENERATOR_VERSION = JSON.parse(fs.readFileSync(new URL('../../package.json', import.meta.url), 'utf8')).version;

export function readLock(projectDir) {
    const file = path.join(projectDir, LOCK_FILE);

    return exists(file) ? readJson(file) : null;
}

export function requireProject(projectDir) {
    const lock = readLock(projectDir);

    if (!lock) {
        throw new Error(`${projectDir} is not a SchoolForge project (no ${LOCK_FILE}). Run this inside a generated project or pass --project <dir>.`);
    }

    return lock;
}

export function readProjectConfig(projectDir) {
    return readJson(path.join(projectDir, PROJECT_CONFIG_FILE));
}

export function writeProjectConfig(projectDir, config) {
    writeJson(path.join(projectDir, PROJECT_CONFIG_FILE), config);
}

function pascalCase(name) {
    return name
        .split('-')
        .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
        .join('');
}

/**
 * Lists the project's own components in `<schoolDir>/custom/<name>/index.tsx`.
 * They are never touched by sync and take precedence over registry components.
 */
export function listCustomComponents(projectDir, target) {
    const dir = path.join(projectDir, target.schoolDir, 'custom');

    if (!exists(dir)) {
        return [];
    }

    return fs
        .readdirSync(dir, { withFileTypes: true })
        .filter((entry) => entry.isDirectory() && ['index.tsx', 'index.jsx'].some((file) => exists(path.join(dir, entry.name, file))))
        .map((entry) => entry.name)
        .sort();
}

export function renderRegistryFile(registryComponents, customComponents) {
    const custom = new Set(customComponents);
    const imports = [];
    const entries = [];

    for (const name of registryComponents.filter((item) => !custom.has(item))) {
        imports.push(`import ${pascalCase(name)} from './components/${name}';`);
        entries.push(`    '${name}': ${pascalCase(name)},`);
    }

    for (const name of customComponents) {
        imports.push(`import Custom${pascalCase(name)} from './custom/${name}';`);
        entries.push(`    '${name}': Custom${pascalCase(name)},`);
    }

    return [
        '// Generated by SchoolForge. Run `schoolforge sync` after adding components to ./custom; do not edit by hand.',
        "import type { ComponentType } from 'react';",
        "import type { SectionProps } from './runtime/types';",
        ...imports,
        '',
        '// eslint-disable-next-line @typescript-eslint/no-explicit-any',
        'export const sectionComponents: Record<string, ComponentType<SectionProps<any>>> = {',
        ...entries,
        '};',
        '',
    ].join('\n');
}

/**
 * Writes the default-language site data plus `site.<code>.json` per extra language,
 * removing files of languages that were dropped. Next.js also gets `sites.ts`, which
 * imports them all; Laravel gets `translations.json` so admin edits can be layered
 * under each translation at runtime.
 */
function writeSiteFiles(projectDir, target, config, defaultLocale, sites) {
    const siteFile = path.join(projectDir, target.siteDataFile);
    const directory = path.dirname(siteFile);
    const locales = Object.keys(sites);

    writeJson(siteFile, sites[defaultLocale]);

    for (const locale of locales.filter((code) => code !== defaultLocale)) {
        writeJson(path.join(directory, `site.${locale}.json`), sites[locale]);
    }

    for (const file of fs.existsSync(directory) ? fs.readdirSync(directory) : []) {
        const match = /^site\.([a-z]{2})\.json$/.exec(file);

        if (match && (!locales.includes(match[1]) || match[1] === defaultLocale)) {
            fs.rmSync(path.join(directory, file));
        }
    }

    if (target.name === 'nextjs') {
        const imports = locales.map((code) => `import ${code} from './${code === defaultLocale ? 'site.json' : `site.${code}.json`}';`);

        writeFile(
            path.join(directory, 'sites.ts'),
            [
                '// Generated by SchoolForge from school.config.json; do not edit by hand.',
                "import type { SiteData } from './runtime/types';",
                ...imports,
                '',
                `export const defaultLocale = '${defaultLocale}';`,
                '',
                `export const sites: Record<string, SiteData> = { ${locales.map((code) => `${code}: ${code} as unknown as SiteData`).join(', ')} };`,
                '',
            ].join('\n'),
        );
    } else {
        writeJson(path.join(directory, 'translations.json'), config.translations ?? {});
    }
}

/**
 * The example school's downloads (examples/files) that the config links to as /files/<name>.
 */
export function sampleFiles(config) {
    const names = new Set();
    const visit = (value) => {
        if (typeof value === 'string') {
            const match = /^\/files\/([A-Za-z0-9][A-Za-z0-9._-]*)$/.exec(value);

            if (match && exists(path.join(SAMPLE_FILES_DIR, match[1]))) {
                names.add(match[1]);
            }
        } else if (value && typeof value === 'object') {
            Object.values(value).forEach(visit);
        }
    };

    visit(config);

    return [...names].sort();
}

/**
 * Brings a generated project in line with its school.config.json and the registry:
 * installs referenced components, applies theme overrides, regenerates theme.css,
 * site data and the component registry. Files the school edited locally are kept
 * unless `force` is set.
 */
export function syncProject(projectDir, { config, force = false, extraComponents = [], dropComponents = [], log = () => {} }) {
    const lock = readLock(projectDir) ?? { files: {}, components: [] };
    const target = getTarget(config.target);
    const theme = getTheme(config.theme);

    if (!theme) {
        throw new Error(`Unknown theme "${config.theme}".`);
    }

    const custom = listCustomComponents(projectDir, target);
    const knownNames = new Set([...listComponents().map((component) => component.name), ...custom]);
    const errors = validateConfig(config, { components: knownNames });

    if (errors.length > 0) {
        throw new Error(`school.config.json has problems:\n  - ${errors.join('\n  - ')}`);
    }

    const resolveComponent = (name) => getComponent(name) ?? (custom.includes(name) ? { name, variants: [], requires: [] } : null);
    const { defaultLocale, sites, warnings } = buildSites(config, theme, { resolveComponent });
    const site = sites[defaultLocale];
    const drop = new Set(dropComponents);
    const wanted = new Set([...(lock.components ?? []), ...usedComponents(site), ...extraComponents].filter((name) => !drop.has(name) && !RETIRED_COMPONENTS.has(name)));
    const missing = [...wanted].filter((name) => !knownNames.has(name));

    if (missing.length > 0) {
        throw new Error(`Unknown component(s): ${missing.join(', ')}. Create them with \`schoolforge new component <name>\` or in ${target.schoolDir}/custom/.`);
    }

    const registryComponents = [...wanted].filter((name) => getComponent(name)).sort();
    const managed = new Map();
    const schoolDir = target.schoolDir;

    for (const file of listFiles(RUNTIME_DIR)) {
        managed.set(`${schoolDir}/runtime/${file}`, path.join(RUNTIME_DIR, file));
    }

    managed.set(`${schoolDir}/adapter.tsx`, target.adapterFile);

    const vars = lock.vars ?? { packageName: slugify(config.project?.name ?? config.school.shortName ?? config.school.name) || 'school-website', schoolName: config.school.name };

    for (const [relative, contents] of target.appFiles?.(vars) ?? []) {
        managed.set(relative, { contents });
    }

    for (const name of registryComponents) {
        const override = theme.componentOverrides[name];
        const sourceDir = override?.dir ?? getComponent(name).dir;

        for (const file of listFiles(sourceDir).filter((item) => item !== 'component.json')) {
            managed.set(`${schoolDir}/components/${name}/${file}`, path.join(sourceDir, file));
        }
    }

    for (const name of sampleFiles(config)) {
        managed.set(`public/files/${name}`, path.join(SAMPLE_FILES_DIR, name));
    }

    const result = { written: [], unchanged: [], skipped: [], removed: [], warnings };
    const nextFiles = {};

    for (const [relative, source] of managed) {
        const dest = path.join(projectDir, relative);
        const contents = typeof source === 'string' ? fs.readFileSync(source) : source.contents;
        const sourceHash = hashContents(contents);
        const currentHash = hashFile(dest);
        const recordedHash = lock.files?.[relative];
        const locallyModified = currentHash !== null && recordedHash !== undefined && currentHash !== recordedHash;

        if (currentHash === sourceHash) {
            result.unchanged.push(relative);
            nextFiles[relative] = sourceHash;
        } else if (locallyModified && !force) {
            result.skipped.push(relative);
            nextFiles[relative] = recordedHash;
        } else {
            writeFile(dest, contents);
            result.written.push(relative);
            nextFiles[relative] = sourceHash;
        }
    }

    for (const [relative, recordedHash] of Object.entries(lock.files ?? {})) {
        if (managed.has(relative)) {
            continue;
        }

        const dest = path.join(projectDir, relative);
        const currentHash = hashFile(dest);

        if (currentHash === null) {
            continue;
        }

        if (currentHash === recordedHash || force) {
            removeFile(dest);
            result.removed.push(relative);
        } else {
            result.skipped.push(relative);
            result.warnings.push(`${relative} was edited locally, so it was left in place although the site no longer uses it.`);
        }
    }

    target.mergePackageJson?.(projectDir, vars);
    writeFile(path.join(projectDir, schoolDir, 'registry.ts'), renderRegistryFile(registryComponents, custom));
    writeFile(path.join(projectDir, schoolDir, 'theme.css'), buildThemeCss(theme, config));
    writeSiteFiles(projectDir, target, config, defaultLocale, sites);

    writeJson(path.join(projectDir, LOCK_FILE), {
        generator: 'schoolforge',
        version: GENERATOR_VERSION,
        target: target.name,
        theme: theme.name,
        vars,
        components: registryComponents,
        custom,
        files: Object.fromEntries(Object.entries(nextFiles).sort(([a], [b]) => a.localeCompare(b))),
    });

    for (const file of result.skipped) {
        log(`  kept local edits: ${file} (use --force to overwrite)`);
    }

    return { ...result, site, sites, components: registryComponents, custom };
}
