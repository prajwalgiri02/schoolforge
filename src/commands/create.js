import fs from 'node:fs';
import path from 'node:path';
import { slugify, TARGETS, validateConfig } from '../lib/config.js';
import { exists, isEmptyDir, readJson, writeFile } from '../lib/fsutil.js';
import { LOCK_FILE } from '../lib/paths.js';
import { syncProject, writeProjectConfig } from '../lib/project.js';
import { getTheme, listComponents } from '../lib/registry.js';
import { getTarget } from '../lib/targets/index.js';

export const help = `schoolforge create <directory> --config <school.config.json> [options]

Generate a new school website codebase.

Options:
  --config, -c <file>   School config (see examples/school.config.json). Required.
  --target <name>       ${TARGETS.join(' | ')} (overrides config.target, default nextjs)
  --theme <name>        Theme to use (overrides config.theme, default classic)
  --skip-install        Only write files; do not run composer / npm
  --build               Also run a production build after installing
  --force               Allow generating into a non-empty directory`;

function projectReadme(config, target, theme) {
    const school = config.school.name;
    const devCommand = target.name === 'nextjs' ? 'npm run dev' : 'composer run dev';

    return `# ${school} website

Generated by **SchoolForge** using the \`${target.name}\` target and the **${theme.label}** theme.

## Run it

\`\`\`bash
${target.name === 'nextjs' ? 'npm install' : 'composer install && npm install && php artisan migrate && php artisan storage:link'}
${devCommand}
\`\`\`

## Edit content
${
    target.name === 'nextjs'
        ? ''
        : `
Staff can edit content in the admin panel at \`/admin\`. Create a login with:

\`\`\`bash
php artisan school:admin office@school.edu
\`\`\`

Admin edits go live immediately. Run \`php artisan school:export-content\` to copy them into
\`school.config.json\` before regenerating the site with SchoolForge.
`
}
All school content (details, colours, programs, faculty, news...) also lives in \`school.config.json\`.
After editing it, regenerate the site data:

\`\`\`bash
schoolforge sync
\`\`\`

## Customise

| Task | Command |
| --- | --- |
| Switch theme | \`schoolforge use-theme <name>\` |
| Add a component (and a section using it) | \`schoolforge add <component> --page /about\` |
| Remove a component everywhere | \`schoolforge remove <component>\` |
| Update components to the latest registry version | \`schoolforge sync\` |
| Build your own component | create \`${target.schoolDir}/custom/<name>/index.tsx\`, then \`schoolforge sync\` |

You can edit any file in \`${target.schoolDir}/components\` directly. \`schoolforge sync\` notices local
edits (tracked in \`${LOCK_FILE}\`) and leaves them alone unless you pass \`--force\`.
\`theme.css\`, \`registry.ts\` and the site data file are regenerated on every sync, so do not edit them.
`;
}

export function createProject({ directory, configFile, target: targetName, theme: themeName, skipInstall = false, build = false, force = false, log = console.log }) {
    if (!directory) {
        throw new Error('Missing <directory>.\n\n' + help);
    }

    if (!configFile) {
        throw new Error('Missing --config <file>. Start from examples/school.config.json or run `schoolforge init`.');
    }

    const config = readJson(path.resolve(configFile));
    config.target = targetName ?? config.target ?? 'nextjs';
    config.theme = themeName ?? config.theme ?? 'classic';
    delete config.$schema;

    const components = new Set(listComponents().map((component) => component.name));
    const errors = validateConfig(config, { components });

    if (errors.length > 0) {
        throw new Error(`Config is invalid:\n  - ${errors.join('\n  - ')}`);
    }

    const target = getTarget(config.target);
    const theme = getTheme(config.theme);
    const projectDir = path.resolve(directory);

    if (exists(path.join(projectDir, LOCK_FILE))) {
        throw new Error(`${projectDir} is already a SchoolForge project. Use \`schoolforge sync\` inside it instead.`);
    }

    const laravelApp = target.name === 'laravel-inertia-react' && exists(path.join(projectDir, 'artisan'));

    if (!force && !laravelApp && !isEmptyDir(projectDir)) {
        throw new Error(`${projectDir} is not empty. Choose a new directory or pass --force.`);
    }

    log(`Creating ${config.school.name} (${target.label}, theme: ${theme.label})`);
    fs.mkdirSync(projectDir, { recursive: true });

    target.prepare?.(projectDir, { skipInstall, log });

    const vars = { packageName: slugify(config.project?.name ?? config.school.shortName ?? config.school.name) || 'school-website', schoolName: config.school.name };
    target.scaffold(projectDir, vars);
    writeProjectConfig(projectDir, config);

    const result = syncProject(projectDir, { config, log });

    for (const warning of result.warnings) {
        log(`  warning: ${warning}`);
    }

    writeFile(path.join(projectDir, 'SCHOOLFORGE.md'), projectReadme(config, target, theme));
    log(`  ${result.site.pages.length} pages, ${result.components.length} components installed`);

    if (!skipInstall) {
        target.install(projectDir, { build, log });
    }

    const relative = path.relative(process.cwd(), projectDir) || '.';
    log('\nDone! Next steps:');

    for (const step of target.nextSteps(relative, { installed: !skipInstall })) {
        log(`  ${step}`);
    }

    return { projectDir, ...result };
}
